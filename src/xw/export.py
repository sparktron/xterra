def is_safety(value: str, unit: str, flag: bool, item: str = "") -> bool:
    """Safety-critical = the extractor said so OR (deterministically) torque, fluid capacity, pressure or
    preload-style values. Do not rely on the model's boolean alone: it defaults to false."""
    text = f"{value} {unit}"
    return flag or bool(_TORQUE.search(text) or _SAFETY_UNITS.search(text) or _SAFETY_ITEMS.search(item))


def load_rows(conn: sqlite3.Connection) -> list[FactRow]:
    verdicts: dict[int, Verdicts] = defaultdict(lambda: defaultdict(dict))
    for v in conn.execute("SELECT fact_id, claim_key, by, verdict FROM verdicts"):
        verdicts[v["fact_id"]][v["claim_key"]][v["by"]] = v["verdict"]
    q = """SELECT f.id, f.thread_id, f.fact_json, c.text AS chunk_text, t.url, t.title, t.author, t.posted,
                  s.id AS sid, s.type AS stype, s.trust
           FROM facts f JOIN chunks c ON c.id=f.chunk_id JOIN threads t ON t.id=f.thread_id JOIN sources s ON s.id=t.source_id
           ORDER BY f.id"""
    fixes = corrections.load_accepted(conn)
    judged = {(r["fact_id"], r["by"]): r["list_hash"] for r in conn.execute("SELECT fact_id, by, list_hash FROM complete_lists")}
    rows = []
    for r in conn.execute(q):
        fact, done = corrections.apply(Fact.model_validate_json(r["fact_json"]), r["thread_id"], r["chunk_text"], fixes)
        fact.years = grounded_years(fact.years, r["chunk_text"])   # re-checked like grounding, so older facts lose post dates
        v = {k: dict(x) for k, x in verdicts.get(r["id"], {}).items()}
        for key, by in done.items():
            v[key] = {by: "corrected"}
        if any(k.startswith("step:") for k in done):   # a `complete` verdict counts only if it judged the corrected list
            want = corrections.claim_hash(dict(claims_for_fact(fact))["complete"])
            v["complete"] = {by: d for by, d in v.get("complete", {}).items() if by != "local" and judged.get((r["id"], by)) == want}
        # grounding is recomputed (not read from facts.grounding_json) so tightened rules reach older facts, and corrections
        rows.append(FactRow(r["id"], r["thread_id"], r["sid"], r["stype"], r["trust"], r["url"], r["title"], r["author"],
                            r["posted"], fact, ground_fact(fact, r["chunk_text"]), v,
                            r["chunk_text"].count("[image:") if is_guide_chunk(r["chunk_text"]) else 0, done, r["chunk_text"]))
    return rows


@dataclass
class Page:
    topic: Topic
    rows: list[FactRow] = field(default_factory=list)
    dropped: list[dict[str, str]] = field(default_factory=list)   # withheld items, with the reason
    pending: list[dict[str, str]] = field(default_factory=list)   # safety-critical values awaiting corroboration/review
    disputes: list[str] = field(default_factory=list)
    single_source_safety: list[str] = field(default_factory=list)   # unconfirmed safety values published (marked)
    unconfirmed: list[dict[str, Any]] = field(default_factory=list)  # the same, with their claim keys, for re-checking
    reviewed_items: int = 0
    partial_items: int = 0


def build_pages(rows: list[FactRow], topics: TopicIndex, generation: str = DEFAULT_GENERATION) -> dict[tuple[str, str], Page]:
    """Pages of one generation's section; `rows` must already be that generation's (see `route_rows`)."""
    pages: dict[tuple[str, str], Page] = {}
    for row in rows:
        topic = topics.resolve(row.fact.topic, row.fact.category, generation)
        pages.setdefault((topic.category, topic.slug), Page(topic)).rows.append(row)
    return pages


def confidence_for(page: Page, contributing: list[FactRow] | None = None) -> str:
    """Confidence counts only rows that contributed at least one PUBLISHED claim."""
    rows = page.rows if contributing is None else contributing
    if page.disputes:
        return "disputed"
    if any(r.source_type == "manufacturer" for r in rows):
        return "confirmed"
    threads = {r.thread_id for r in rows}
    authors = {r.author.strip().lower() for r in rows if r.author.strip()}
    if len(threads) >= 2 and len(authors) >= 2:
        return "community-consensus"
    return "[Unverified]"


def _fmt_src(sids: list[str]) -> str:
    return f" [{', '.join(sids)}]" if sids else ""


def _metadata_comment(fm: dict[str, Any]) -> list[str]:
    """A page's metadata as lines of an HTML comment. GitHub takes YAML as front matter only when `---` is the file's
    first line, and GENERATED has to be first, so uncommented it prints as text above the heading. A value that could
    close the comment loses a hyphen here; the page body keeps the original. qa._metadata_end parses this layout."""
    return ["<!--", "---", COMMENT_END.sub("->", yaml.safe_dump(fm, sort_keys=False, allow_unicode=True).strip()), "---", "-->"]


def _flat(s: str) -> str:
    """A part name or note as rendered. qa.PART_LINE reads a trailing "(...)" as the part number, so parentheses must
    not survive (a numberless part "Wire: (12 AWG or larger)" once failed qa that way)."""
    return re.sub(r"\s*\(([^)]*)\)", r", \1", s).lstrip(", ").replace("(", "").replace(")", "")


def _tagged(text: str, tag: str) -> str:
    return f"{text} ({tag})" if tag else text


@dataclass
class PageModel:
    """Gated data for a page, independent of the Markdown representation."""
    title: str
    guide: str
    metadata: dict[str, Any]
    lists: dict[str, Any]
    procedures: list[dict[str, Any]]
    parts: list[dict[str, Any]]
    specifications: list[dict[str, Any]]
    diagrams: list[tuple[str, str]]
    sources: list[dict[str, Any]]
    unconfirmed_values: list[tuple[str, str]]
    withheld: list[dict[str, str]]
    pending: list[dict[str, Any]]
    unconfirmed: list[dict[str, Any]]
    single_source_safety: list[str]


def build_page_model(page: Page, scope_years: tuple[int, int], policy: Policy,
                gens: list[Generation] | None = None, guide: str = "") -> PageModel:
    """`gens`: every generation of the wiki. A claim that names a generation other than the page's is withheld, so
    one generation's facts never publish in the other's section (qa re-checks this). `guide`: the page-relative link to
    the curated guide for this topic, if one exists; it is linked above the summary."""
    rows = sorted(page.rows, key=lambda r: (-r.trust, r.id))
    drop = lambda r, kind, text, why: page.dropped.append({"kind": kind, "text": text[:160], "url": r.url, "why": why})  # noqa: E731
    gen = next((g for g in gens or [] if g.id == page.topic.generation), None)

    def other_gen(text: str) -> str:
        o = other_marker(text, gen, gens or []) if gen else None
        return f"names the {o.title}; this page is the {gen.title}" if o and gen else ""

    summaries: list[tuple[str, str, bool]] = []      # (text, sid, published on a `partial` verdict)
    steps_by_row: list[tuple[FactRow, list[str], list[bool]]] = []
    partial_ids: set[int] = set()   # procedures with a [Partial] step or completeness
    symptoms: list[tuple[str, str, bool]] = []
    tips: list[tuple[str, str, bool]] = []
    mistakes: list[tuple[str, str, bool]] = []
    tools: list[tuple[str, str, bool]] = []
    parts: dict[str, dict[str, Any]] = {}
    specs: dict[str, dict[str, Any]] = {}
    diagrams: list[tuple[str, str]] = []
    contrib: set[int] = set()   # fact-row ids that contributed a published claim

    # pass 1: values (parts, specs, diagrams)
    part_rows: list[tuple[FactRow, int, Any]] = []
    for r in rows:
        f, g, sid = r.fact, r.grounding, r.sid
        for i, p in enumerate(f.parts):
            if not g["parts"][i]:
                drop(r, "part", f"{p.name} {p.part_number}", "part number/evidence not found in source")
                continue
            if why := other_gen(f"{p.name} {p.notes}"):
                drop(r, "part", f"{p.name} {p.part_number}", why)
                continue
            ok, tag, why = gate(r, f"part:{i}", policy)
            if not ok:
                drop(r, "part", f"{p.name} {p.part_number}", why)
                continue
            part_rows.append((r, i, tag))

        for i, s in enumerate(f.specs):
            label = f"{s.item}: {s.value} {s.unit}".strip()
            if not g["specs"][i]:
                drop(r, "spec", label, "value/unit/evidence not found in source")
                continue
            if why := other_gen(label):
                drop(r, "spec", label, why)
                continue
            ok, tag, why = gate(r, f"spec:{i}", policy)
            if not ok:
                drop(r, "spec", label, why)
                continue
            slot = specs.setdefault(_norm(s.item), {"item": s.item, "values": {}, "safety": False})
            v = slot["values"].setdefault(_norm_value(s.value, s.unit), {
                "display": f"{s.value} {s.unit}".strip(), "sids": [], "threads": set(), "authors": set(), "reviewed": "",
                "manufacturer": False, "url": r.url, "rids": set(), "keys": [], "partial": True})
            if sid not in v["sids"]:
                v["sids"].append(sid)
            v["threads"].add(r.thread_id)
            if r.author.strip():
                v["authors"].add(r.author.strip().lower())
            v["rids"].add(r.id)
            v["keys"].append((r.id, f"spec:{i}"))
            v["reviewed"] = v["reviewed"] or (tag if _reviewed(tag) else "")
            v["partial"] = v["partial"] and tag == PARTIAL     # partial only if every report of the value is
            v["manufacturer"] = v["manufacturer"] or r.source_type == "manufacturer"
            slot["safety"] = slot["safety"] or is_safety(s.value, s.unit, s.safety_critical, s.item)

        for i, u in enumerate(f.diagram_links):
            if g["diagrams"][i]:
                diagrams.append((u, sid))

    # specs: corroboration, disputes, and the safety-critical gate
    specifications: list[dict[str, Any]] = []
    published: set[tuple[str, str]] = set()   # (number, unit) of every published spec value on this page
    unconfirmed_values: set[tuple[str, str]] = set()   # ... of those, the safety values published unconfirmed
    for slot in sorted(specs.values(), key=lambda s: s["item"].lower()):
        vals = list(slot["values"].values())
        strict = slot["safety"] and not policy.publish_unverified_safety
        if len(vals) > 1:
            approved = [v for v in vals if v["reviewed"]]
            if len(approved) == 1:
                vals = approved  # a reviewer settled the disagreement
            elif slot["safety"]:   # a disputed safety value is withheld whatever publish_unverified_safety says
                page.disputes.append(slot["item"])
                page.pending.append({"item": slot["item"], "value": " vs ".join(v["display"] for v in vals),
                                     "why": "sources disagree", "url": vals[0]["url"], "keys": [k for v in vals for k in v["keys"]]})
                continue
            else:
                page.disputes.append(slot["item"])
                specifications.append({"item": slot["item"], "alternatives": [{"display": v["display"], "sids": v["sids"]} for v in vals]})
                continue
        v = vals[0]
        n = len(v["threads"])
        # independent reports: distinct threads AND distinct (known) authors, so one person cross-posting
        # the same number in two threads is not consensus
        n_ind = min(n, len(v["authors"]))
        if v["reviewed"]:
            tag = v["reviewed"]
        elif v["manufacturer"]:
            tag = "manufacturer source"
        elif n_ind >= 2 and (not strict or n_ind >= policy.safety_min_threads):
            tag = f"community-consensus, {n} threads"
        elif strict and n_ind < policy.safety_min_threads:
            need = policy.safety_min_threads
            why = (f"only {n} thread(s); needs {need} or a review" if n < need else
                   f"{n} threads but {len(v['authors'])} distinct known author(s); needs {need} independent reports or a review")
            page.pending.append({"item": slot["item"], "value": v["display"], "why": why, "url": v["url"], "keys": v["keys"]})
            continue
        else:
            tag = "[Unverified] single report" if n == 1 else "[Unverified] not independently corroborated"
        if v["partial"]:
            tag = f"{PARTIAL} {tag}"
            page.partial_items += 1
        confirmed = bool(v["reviewed"]) or v["manufacturer"] or (n_ind >= policy.safety_min_threads and not v["partial"])
        if slot["safety"] and not confirmed and not v["partial"] and "[Unverified]" not in tag:
            # consensus below a raised safety_min_threads (Codex review of #9): the tag must not read as confirmed
            tag = f"[Unverified] {tag}, needs {policy.safety_min_threads}"
        if slot["safety"] and not confirmed:   # published marked; stays queued until a second source or a review
            page.single_source_safety.append(f"{slot['item']}: {v['display']}")
            page.unconfirmed.append({"item": slot["item"], "value": v["display"], "url": v["url"], "keys": v["keys"],
                                     "why": f"published marked ({tag}); needs {policy.safety_min_threads} independent reports or a review"})
            unconfirmed_values |= safety_values(v["display"])
        page.reviewed_items += bool(v["reviewed"])
        contrib |= v["rids"]
        published |= safety_values(v["display"])
        specifications.append({"item": slot["item"], "display": v["display"], "sids": v["sids"], "tag": tag})

    def loose(text: str, source: str) -> str:
        """Why `text` may not publish: it states a torque/capacity/pressure value that is not a published spec here.
        With publish_unverified_safety such a value may still publish if the source puts that unit on that number: it
        is then an unconfirmed value (marked [Unverified value] by `mark`, re-checked by the review queue)."""
        extra = safety_values(text) - published
        if not extra:
            return ""
        if policy.publish_unverified_safety:
            if unit_grounded(text, "", source):
                unconfirmed_values.update(extra)
                return ""
            return "safety-critical value the source does not state with that unit: " + ", ".join(f"{n} {u}" for n, u in sorted(extra))
        return "safety-critical value not published as a corroborated spec: " + ", ".join(f"{n} {u}" for n, u in sorted(extra))

    for r, i, tag in part_rows:
        p = r.fact.parts[i]
        # judge the name and note as rendered: "(3) Quarts Gear Oil" prints as "3 Quarts Gear Oil", which states 3 qt
        why = loose(_flat(p.name), r.text)
        if why:
            drop(r, "part", f"{p.name} {p.part_number}", why)
            continue
        page.reviewed_items += _reviewed(tag)
        contrib.add(r.id)
        key = _norm(p.part_number) or _norm(p.name)
        slot = parts.setdefault(key, {"name": p.name, "part_number": p.part_number, "notes": [], "sids": [], "partial": True})
        slot["partial"] = slot["partial"] and tag == PARTIAL
        if p.notes and loose(_flat(p.notes), r.text):
            drop(r, "part note", p.notes, loose(_flat(p.notes), r.text))
        elif p.notes and p.notes not in slot["notes"]:
            slot["notes"].append(p.notes)
        if r.sid not in slot["sids"]:
            slot["sids"].append(r.sid)

    # pass 2: prose. Copied text, a number missing from the source, a verifier miss, or a loose safety value withholds it.
    def prose(r: FactRow, key: str, text: str, copied: bool, numbers_ok: bool) -> tuple[bool, str, str]:
        if why := other_gen(text):
            return False, "", why
        if copied:
            return False, "", "verbatim overlap with source"
        if not numbers_ok:
            return False, "", "number not found in source"
        ok, tag, why = gate(r, key, policy)
        if not ok:
            return False, "", why
        why = loose(text, r.text)
        return (False, "", why) if why else (True, tag, "")

    for r in rows:
        f, g, sid = r.fact, r.grounding, r.sid
        copied, nums = g["copied"], g["numbers"]

        if f.summary.strip():
            ok, tag, why = prose(r, "summary", f.summary, copied["summary"], nums["summary"])
            if ok:
                page.reviewed_items += _reviewed(tag)
                summaries.append((f.summary, sid, tag == PARTIAL))
                contrib.add(r.id)
            else:
                drop(r, "summary", f.summary, why)

        # procedure: every step must publish (one withheld step withholds the whole procedure). A step or completeness
        # claim the verifier only partly supports publishes marked [Partial] until a later verify/review upgrades it;
        # `unsupported` or a reviewer's reject still withholds it. An empty step (the model sometimes returns "") is not
        # a claim and is skipped; verdicts stay keyed by the stored index.
        has_steps = any(s.strip() for s in f.steps)
        proc_ok = has_steps
        shown: list[str] = []
        step_partial: list[bool] = []
        for i, step in enumerate(f.steps):
            if not step.strip():
                continue
            ok, tag, why = prose(r, f"step:{i}", step, copied["steps"][i], nums["steps"][i])
            if not ok:
                proc_ok = False
                drop(r, f"step {i + 1} (procedure withheld)", step, why)
            page.reviewed_items += bool(ok and _reviewed(tag))
            shown.append(step)
            step_partial.append(ok and tag == PARTIAL)
        if has_steps:
            ok, tag, why = gate(r, "complete", policy)
            partial_list = (ok and tag == PARTIAL) or (not ok and is_partial_completeness(r))
            if not ok and not (proc_ok and partial_list):
                proc_ok = False
                drop(r, "completeness (procedure withheld)", "; ".join(f.steps), why)
            if partial_list or any(step_partial):
                partial_ids.add(r.id)
        steps_by_row.append((r, shown if proc_ok else [], step_partial))
        if proc_ok:
            contrib.add(r.id)

        for key, lst, dest in (("symptom", f.symptoms, symptoms), ("tip", f.tips, tips), ("mistake", f.mistakes, mistakes),
                               ("tool", f.tools, tools)):
            for i, text in enumerate(lst):
                if not text.strip():
                    continue
                ok, tag, why = prose(r, f"{key}:{i}", text, key != "tool" and copied[f"{key}s"][i], nums[f"{key}s"][i])
                if ok:
                    page.reviewed_items += _reviewed(tag)
                    dest.append((text, sid, tag == PARTIAL))
                    contrib.add(r.id)
                else:
                    drop(r, key, text, why)

        for key, present, label in (("applies", bool(f.years or f.trims or f.engines or f.drivetrain), "applicability"),
                                    ("platform", bool(f.shared_platform), "shared platform")):
            if present and not gate(r, key, policy)[0]:
                drop(r, label, ", ".join(map(str, f.years + f.trims + f.engines + f.drivetrain)) if key == "applies"
                     else ", ".join(f.shared_platform), gate(r, key, policy)[2])

    proc = [(r, s, sp) for r, s, sp in steps_by_row if s]
    proc.sort(key=lambda rs: (rs[0].id in partial_ids, -len(rs[1]), -rs[0].trust, rs[0].id))   # complete before partial

    # metadata is published only from facts whose metadata claim passed the gate; a field fed by a `partial` verdict is
    # listed in verification.partial_fields
    applies = [r for r in rows if gate(r, "applies", policy)[0]]
    platform = [r for r in rows if gate(r, "platform", policy)[0]]
    years = sorted({y for r in applies for y in r.fact.years if scope_years[0] <= y <= scope_years[1]})
    diffs = sorted(r.fact.difficulty for r in rows if r.fact.difficulty and gate(r, "difficulty", policy)[0])
    est = Counter(r.fact.est_time for r in rows if r.fact.est_time and gate(r, "time", policy)[0]).most_common(1)
    partial_fields = sorted(name for name, key, used in (
        ("applies_to", "applies", [r for r in applies if r.fact.years or r.fact.trims or r.fact.engines or r.fact.drivetrain]),
        ("shared_platform", "platform", platform),
        ("difficulty", "difficulty", [r for r in rows if r.fact.difficulty]),
        ("est_time", "time", [r for r in rows if r.fact.est_time])) if any(gate(r, key, policy)[1] == PARTIAL for r in used))
    # count what the page body prints marked [Partial] (deduplicated, as rendered)
    lists = {name: _dedupe_marked(items) for name, items in (("summary", summaries), ("symptom", symptoms), ("tip", tips),
                                                                ("mistake", mistakes), ("tool", tools))}
    page.partial_items += sum(part for items in lists.values() for _, _, part in items)
    page.partial_items += sum(1 for p in parts.values() if p["partial"])
    if proc:
        page.partial_items += sum(proc[0][2]) + (proc[0][0].id in partial_ids and not any(proc[0][2]))
    conf = confidence_for(page, [r for r in rows if r.id in contrib])

    def meta(src: list[FactRow], field: str) -> list[str]:
        """Verified metadata values for the front matter, minus any that name another generation (dropped, listed)."""
        out: set[str] = set()
        for r in src:
            for v in getattr(r.fact, field):
                if why := other_gen(str(v)):
                    drop(r, field, str(v), why)
                else:
                    out.add(v)
        return sorted(out)

    trims, engines, drivetrain = meta(applies, "trims"), meta(applies, "engines"), meta(applies, "drivetrain")
    shared = meta(platform, "shared_platform")
    fm = {
        "title": page.topic.title,
        "generation": page.topic.generation,
        "category": page.topic.category,
        "applies_to": {"years": years, "trims": trims, "engine": engines, "drivetrain": drivetrain},
        "shared_platform": shared,
        "difficulty": diffs[len(diffs) // 2] if diffs else None,
        "est_time": est[0][0] if est else None,
        "tools": [t for t, _, _ in lists["tool"]],
        "parts": [{"name": p["name"], "oem_part_no": p["part_number"]} for p in sorted(parts.values(), key=lambda p: p["name"].lower())],
        "sources": sorted({r.sid for r in rows}, key=lambda s: int(s[1:])),
        "confidence": conf,
        "verification": {"local_pass_required": policy.require_local_pass, "reviewed_items": page.reviewed_items,
                         "partial_items": page.partial_items, "partial_fields": partial_fields,
                         "unconfirmed_safety_values": len(page.unconfirmed),
                         "withheld_items": len(page.dropped), "pending_safety_values": len(page.pending)},
    }

    source_rows = {r.thread_id: r for r in reversed(sorted(rows, key=lambda r: r.thread_id))}
    sources = [{"sid": r.sid, "author": r.author, "posted": r.posted, "thread_title": r.thread_title, "url": r.url}
               for _, r in sorted(source_rows.items())]
    procedures = [{"sid": r.sid, "url": r.url, "photos": r.photos,
                   "corrected_steps": sum(k.startswith("step:") for k in r.corrected),
                   "partial": r.id in partial_ids, "steps": steps, "step_partial": step_partial}
                  for r, steps, step_partial in proc]
    # Skip near-duplicate alternates at the gate so the model contains only published procedures.
    if procedures:
        procedures = [procedures[0]] + [p for p in procedures[1:]
                     if not _similar(" ".join(p["steps"]), " ".join(procedures[0]["steps"]), 0.85)]
    return PageModel(page.topic.title, guide, fm, lists, procedures, list(parts.values()), specifications,
                     sorted(set(diagrams)), sources, sorted(unconfirmed_values), list(page.dropped),
                     list(page.pending), list(page.unconfirmed), list(page.single_source_safety))


def render_model(model: PageModel) -> tuple[str, dict[str, Any]]:
    """Render an already-gated page without consulting the database or policy."""
    fm, guide, lists = model.metadata, model.guide, model.lists
    conf = fm["confidence"]
    partial_fields = fm["verification"]["partial_fields"]
    unconfirmed_values = set(map(tuple, model.unconfirmed_values))
    proc, parts, diagrams = model.procedures, model.parts, model.diagrams

    def mark(text: str, partial: bool) -> str:
        unverified = bool(safety_values(text) & unconfirmed_values)
        return (f"{PARTIAL} " if partial else "") + (f"{UNVERIFIED_VALUE} " if unverified else "") + text

    out = [GENERATED, *_metadata_comment(fm), "", f"# {model.title}", ""]
    if guide:
        out += [f"> **Guide for this job:** [{model.title}]({guide}) is a hand-written guide that cites every step and "
                "number. This page collects what forum threads add.", ""]
    if conf == "[Unverified]":
        out += ["> **[Unverified]** This page rests on a single community report. Cross-check before relying on it.", ""]
    if model.single_source_safety or unconfirmed_values:
        out += [SAFETY_NOTE, ""]
    if fm["verification"]["partial_items"] or partial_fields:
        out += [PAGE_PARTIAL_NOTE, ""]
    if model.pending:
        out += ["> Some safety-critical values for this topic are withheld until verified. See `pending_verification.md`.", ""]
    out += ["## Summary", ""]
    if lists["summary"]:
        for text, sids, part in lists["summary"]:
            out += [f"{mark(text, part)}{_fmt_src(sids)}", ""]
    else:
        out += ["_No verified summary yet._", ""]
    if lists["symptom"]:
        out += ["## Symptoms / When you need this", ""] + [f"- {mark(t, part)}{_fmt_src(s)}" for t, s, part in lists["symptom"]] + [""]
    if proc:
        r0 = proc[0]
        steps0, partial0 = r0["steps"], r0["step_partial"]
        out += ["## Procedure", ""]
        if r0["partial"]:
            out += [PARTIAL_NOTE, ""]
        # the wiki rewrites the steps and does not copy the author's photos; it says where they are
        pics = f" Photos of this job are in the source: <{r0['url']}>" if r0["photos"] else ""
        n = r0["corrected_steps"]
        fixed = f"; {n} step{'s' if n != 1 else ''} reworded by a reviewer" if n else ""
        out += [f"{i}. {mark(s, pt)}" for i, (s, pt) in enumerate(zip(steps0, partial0), 1)] + \
            ["", f"_Procedure reported by [{r0['sid']}]{fixed}.{pics}_", ""]
        for r in proc[1:]:
            s, sp = r["steps"], r["step_partial"]
            alt = " [Partial]" if r["partial"] else ""
            out += [f"<details><summary>Alternate procedure [{r['sid']}]{alt}</summary>", ""] + \
                [f"{i}. {mark(x, pt)}" for i, (x, pt) in enumerate(zip(s, sp), 1)] + ["", "</details>", ""]
    if fm["tools"]:
        out += ["## Tools", ""] + [f"- {mark(t, part)}{_fmt_src(s)}" for t, s, part in lists["tool"]] + [""]
    if parts:
        out += ["## Parts", ""]
        for p in sorted(parts, key=lambda p: p["name"].lower()):
            pn = f" ({p['part_number']})" if p["part_number"] else ""
            note = f": {'; '.join(_flat(n) for n in p['notes'])}" if p["notes"] else ""
            name = _flat(p["name"])
            out.append(f"- {mark(f'{name}{pn}{note}', p['partial'])}{_fmt_src(p['sids'])}")
        out.append("")
    if model.specifications:
        out += ["## Specifications", ""]
        for spec in model.specifications:
            if "alternatives" in spec:
                alts = "; ".join(f"{v['display']}{_fmt_src(v['sids'])}" for v in spec["alternatives"])
                out.append(f"- **{spec['item']}**: DISPUTED, sources disagree: {alts}")
            else:
                out.append(f"- **{spec['item']}**: {spec['display']}{_fmt_src(spec['sids'])} ({spec['tag']})")
        out.append("")
    if lists["tip"]:
        out += ["## Tips & gotchas", ""] + [f"- {mark(t, part)}{_fmt_src(s)}" for t, s, part in lists["tip"]] + [""]
    if lists["mistake"]:
        out += ["## Common mistakes", ""] + [f"- {mark(t, part)}{_fmt_src(s)}" for t, s, part in lists["mistake"]] + [""]
    if diagrams:
        out += ["## Diagrams (links only)", ""] + [f"- {u} [{s}]" for u, s in sorted({tuple(d) for d in diagrams})] + [""]
    out += ["## Source attributions", ""]
    for source in model.sources:
        who = f"{source['author']}, " if source['author'] else ""
        when = f", {source['posted'][:10]}" if source['posted'] else ""
        out.append(f"- **{source['sid']}**: {who}\"{source['thread_title']}\"{when}. {source['url']}")
    out.append("")
    return "\n".join(out), {"confidence": conf, "n_threads": len(model.sources), "years": fm["applies_to"]["years"]}



def render_page(page: Page, scope_years: tuple[int, int], policy: Policy,
                gens: list[Generation] | None = None, guide: str = "") -> tuple[str, dict[str, Any]]:
    """Compatibility wrapper for callers needing the gate and renderer together."""
    return render_model(build_page_model(page, scope_years, policy, gens, guide))


