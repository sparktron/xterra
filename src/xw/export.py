@dataclass
class Policy:
    require_local_pass: bool = True
    safety_min_threads: int = 2
    publish_unverified_safety: bool = True
    publish_partial: bool = True

    @classmethod
    def from_cfg(cls, cfg: Config) -> "Policy":
        v = cfg.verify
        return cls(bool(v.require_local_pass), int(v.safety_min_threads), bool(v.get("publish_unverified_safety", True)),
                   bool(v.get("publish_partial", True)))


PARTIAL = "[Partial]"            # gate tag: published on the local verifier's `partial` (needs more work)
UNVERIFIED_VALUE = "[Unverified value]"   # prose stating a safety value whose spec is not confirmed


Verdicts = dict[str, dict[str, str]]  # claim_key -> {by: verdict}


@dataclass
class FactRow:
    id: int
    thread_id: int
    source_id: str
    source_type: str
    trust: int
    url: str
    thread_title: str
    author: str
    posted: str
    fact: Fact
    grounding: dict[str, Any]
    verdicts: Verdicts = field(default_factory=dict)
    photos: int = 0   # `[image: ...]` markers in the fact's chunk when it is the author's guide (at most 10 per post kept)
    corrected: dict[str, str] = field(default_factory=dict)   # claim_key -> who reworded it (corrections.py)
    text: str = ""   # the chunk the fact came from

    @property
    def sid(self) -> str:
        return f"t{self.thread_id}"


def gate(row: FactRow, key: str, policy: Policy) -> tuple[bool, str, str]:
    """(publishable, review_tag, why_withheld). A human verdict decides alone, then Claude's, then the local verifier.
    A corrected claim carries only its corrector's `corrected` mark: the other verdicts judged the old wording."""
    v = row.verdicts.get(key, {})
    for by in ("human", "claude"):
        d = v.get(by)
        if d == "approve":
            return True, f"{by.capitalize()}-reviewed", ""
        if d == "corrected":
            return True, f"{by.capitalize()}-corrected", ""
        if d in ("reject", "needs_human"):
            return False, "", f"{by} review: {d}"
    if not policy.require_local_pass:
        return True, "", ""
    local = v.get("local")
    if local == "supported":
        return True, "", ""
    if local == "partial" and policy.publish_partial:
        return True, PARTIAL, ""
    return False, "", f"local verifier: {local or 'not run'}"


def _reviewed(tag: str) -> bool:
    return bool(tag) and tag != PARTIAL


def is_partial_completeness(row: FactRow) -> bool:
    """True when the steps are accurate but the list may leave something out, so the procedure publishes marked
    [Partial]. A reviewer's `needs_human` on `complete` means exactly that ("every step is stated, the list may be
    incomplete"); their `reject` means a listed step is NOT in the source, and `unsupported` from the local verifier
    is not trusted to mean the lesser thing. The first decisive human/claude verdict decides, as in `gate`."""
    v = row.verdicts.get("complete", {})
    for by in ("human", "claude"):
        d = v.get(by)
        if d in ("approve", "reject"):
            return False
        if d == "needs_human":
            return True
    return v.get("local") == "partial"


def _norm(s: str) -> str:
    return re.sub(r"\W+", " ", s.lower()).strip()


def _norm_value(value: str, unit: str) -> str:
    v = f"{value} {unit}".lower()
    v = re.sub(r"ft[\s.\-·]*lbs?|lb[\s.\-·]*ft", "ftlb", v)
    v = re.sub(r"\bn[\s.\-·]*m\b", "nm", v)
    return re.sub(r"[\s,]+", "", v)


def _similar(a: str, b: str, threshold: float) -> bool:
    """Near-identical wording AND the same numbers. "Torque to 150 ft-lb" and "Torque to 180 ft-lb" are a
    disagreement, not a duplicate; merging them would cite the dissenting thread as support."""
    return sorted(number_tokens(a)) == sorted(number_tokens(b)) and SequenceMatcher(None, _norm(a), _norm(b)).ratio() >= threshold


def _dedupe_marked(items: list[tuple[str, str, bool]]) -> list[tuple[str, list[str], bool]]:
    """items: (text, sid, partial). Like `_dedupe`; a merged item is partial only if every report of it was."""
    kept: list[tuple[str, list[str], list[bool]]] = []
    for text, sid, part in items:
        for k, sids, parts in kept:
            if _similar(text, k, 0.88):
                if sid not in sids:
                    sids.append(sid)
                parts.append(part)
                break
        else:
            kept.append((text.strip(), [sid], [part]))
    return [(t, sids, all(parts)) for t, sids, parts in kept]


def _dedupe(items: list[tuple[str, str]]) -> list[tuple[str, list[str]]]:
    """items: (text, sid). Near-duplicate texts merge; returns (text, [sids])."""
    kept: list[tuple[str, list[str]]] = []
    for text, sid in items:
        for k, sids in kept:
            if _similar(text, k, 0.88):
                if sid not in sids:
                    sids.append(sid)
                break
        else:
            kept.append((text.strip(), [sid]))
    return kept


_SAFETY_UNITS = re.compile(r"(\b(qts?|quarts?|liters?|litres?|gal(lons?)?|pints?|fl\.?\s*oz|ml|psi|kpa|bar)\b|\d\s*l\b)", re.I)
_SAFETY_ITEMS = re.compile(r"(torque|tighten|capacity|preload|backlash|end[\s-]?play|pressure|clearance|refill|fill)", re.I)


